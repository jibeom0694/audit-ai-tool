export type IsaEntry = { code: string; title: string; summary: string };

/** 인용 문자열에서 기준서 번호를 뽑아 화이트리스트와 대조한다. 목록에 없으면
 * (= 실재하지 않거나 이 도구가 다루지 않는 기준서) null. */
export function resolveIsaReference(reference: string): IsaEntry | null {
  const match = String(reference ?? "").match(/(\d{3})/);
  if (!match) return null;
  const entry = ISA_STANDARDS[match[1]];
  return entry ? { code: match[1], ...entry } : null;
}

/** 화이트리스트에 있으면 "ISA 520 분석적 절차" 형태의 한글 표기를 돌려준다.
 * 없으면 null — 호출부는 원문을 그대로 노출하지 말고 대체 문구를 써야 한다. */
export function formatIsaReferenceKo(reference: string): string | null {
  const entry = resolveIsaReference(reference);
  return entry ? `ISA ${entry.code} ${entry.title}` : null;
}

/** LLM 프롬프트에 넣을 허용 기준서 목록. */
export const ISA_ALLOWED_LIST = Object.entries(ISA_STANDARDS)
  .map(([code, { title }]) => `ISA ${code} ${title}`)
  .join(" / ");
