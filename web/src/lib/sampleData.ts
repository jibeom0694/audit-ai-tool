// 재무상태표·시산표를 그 위에서 역산했다 — 그래서 세 문서가 서로 대사(tie-out)된다:
//
//   · 전표 → 시산표: 계정별 Σ차변/Σ대변이 시산표의 당기차변/당기대변과 정확히
//     일치한다(예: 매출채권 전표 합계 166,834,700원 = 시산표 매출채권 당기차변).
//   · 시산표 → 재무제표: 시산표 기초/기말잔액이 재무제표 전기/당기 금액과
//     일치한다(부채·자본은 시산표에서 음수로 저장하는 부호규약만 다르다).
//   · 현금흐름표 → 재무제표: CF의 기초/기말현금이 BS 현금 전기/당기와 일치한다.
//
// 시산표는 결산분개(당기순이익의 이익잉여금 반영) 이전 상태를 나타낸다.
// 그래서 시산표의 이익잉여금은 전기·당기가 같고(변동 없음), 재무제표(사후
// 확정본)의 이익잉여금 당기 값만 자산=부채+자본 항등식이 성립하도록 별도로
// 계산했다 — 실제 감사에서도 조정후시산표(TB) → 결산분개 → 최종 재무제표
// 순서로 진행되며, 이 사이의 간극이 조서 초안 단계에서 흔히 발견되는 지점이다.
//
// 전표는 매출채권 발생(외상매출) 6건만 기록되어 있고 회수(현금 수령) 전표가
// 없다 — 그래서 매출채권이 당기에 크게 증가한다. 이건 버그가 아니라 "회수
// 전표가 아예 없는 모집단"이라는 의도된 완전성 결함이며, 전표(JE) 테스트가
// 이런 걸 잡아내야 한다는 걸 보여주는 예시로 남겨두었다.
//
